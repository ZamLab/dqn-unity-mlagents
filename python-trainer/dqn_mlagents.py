# Hyper parameters: batch size, discount factor, eps-greedy, target network update, learning rate
BATCH_SIZE = 128
GAMMA = 0.99
EPS_START = 0.9
EPS_END = 0.05
EPS_DECAY = 1000
TAU = 0.005
LR = 1e-4


n_actions = env.action_space.n
state = env.reset()
n_observations = len(state)


# Replay memory
class ReplayMemory(object):
    def __init__(self, capacity):
        self.memory = deque([], maxlen=capacity)

    def push(self, *args):
        self.memory.append(Transition(*args))

    def sample(self, batch_size):
        return random.sample(self.memory, batch_size)

    def __len__(self):
        return len(self.memory)


# Neural network using ReLU activation functions and 2 hidden layers.
# neurons per layer: npl
if(args.n256):
    npl = 256
else:
    npl = 128


class DQN(nn.Module):

    def __init__(self, n_observations, n_actions):
        super(DQN, self).__init__()
        self.layer1 = nn.Linear(n_observations, npl)
        self.layer2 = nn.Linear(npl, npl)
        self.layer3 = nn.Linear(npl, npl)
        self.layer4 = nn.Linear(npl, n_actions)

    def forward(self, x):
        x = F.relu(self.layer1(x))
        x = F.relu(self.layer2(x))
        x = F.relu(self.layer3(x))
        return self.layer4(x)


policy_net = None
target_net = None
policy_net = DQN(n_observations, n_actions).to(device)
target_net = DQN(n_observations, n_actions).to(device)

model = DQN(n_observations, n_actions).to(device)

target_net.load_state_dict(policy_net.state_dict())

# Initialize AdamW optimizer: a gradient-descent-based method using weight regularization
optimizer = optim.AdamW(policy_net.parameters(), lr=LR, amsgrad=True)
memory = ReplayMemory(10000)

steps_done = 0

"""WrapperNet is used to export the .onnx file in a form compatible with
ML-Agents (2.0.1) Brains. The form must match the .onnx files generated by
the default ML-Agents trainers."""


class WrapperNet(torch.nn.Module):
    def __init__(
            self,
            policy_net: DQN,
            discrete_output_sizes: [int],
    ):
        """
        Wraps the network adding extra constants and dummy mask inputs
        required by runtime inference with Sentis.

        For environments with continuous actions, outputs would need to be
        added similarly to how discrete action outputs work, both in the
        wrapper and in the ONNX output_names / dynamic_axes.
        """
        super(WrapperNet, self).__init__()
        self.policy_net = policy_net

        version_number = torch.Tensor([3])
        self.version_number = Parameter(version_number, requires_grad=False)

        memory_size = torch.Tensor([0])
        self.memory_size = Parameter(memory_size, requires_grad=False)

        output_shape = torch.Tensor([discrete_output_sizes])
        self.discrete_shape = Parameter(output_shape, requires_grad=False)

    # For discrete actions ML-Agents expects a corresponding mask tensor
    # with the same shape to exist as input.
    def forward(self, visual_obs: torch.tensor, mask: torch.tensor):
        qnet_result = self.policy_net(visual_obs)
        # Connect mask to keep it from getting pruned.
        # Mask values will be 1 if you never call SetActionMask() in
        # WriteDiscreteActionMask()
        qnet_result = torch.mul(qnet_result, mask)
        action = torch.argmax(qnet_result, dim=1, keepdim=True)
        return [action], self.discrete_shape, self.version_number, self.memory_size


