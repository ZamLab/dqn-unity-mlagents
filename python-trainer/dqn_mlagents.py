"""
Select action using an eps-greedy policy.
Exploration to exploitation.
"""


def select_action(state):
    global steps_done
    sample = random.random()
    eps_threshold = EPS_END + (EPS_START - EPS_END) * \
        math.exp(-1 * steps_done / EPS_DECAY)
    steps_done += 1
    if sample > eps_threshold:
        with torch.no_grad():
            return policy_net(state).max(1).indices.view(1, 1)
    else:  # Choose random action:
        return torch.tensor([[env.action_space.sample()]], device=device, dtype=torch.long)


""" Save the trained model to an .onnx file which can be transferred to a
Unity project (Behavior Parameters > Model) and run in inference in a Unity
application. The form must match the .onnx files generated by the default
ML-Agents trainers."""


def save_model_onnx():
    example_inp = torch.randn(1, n_observations)

    torch.onnx.export(
        WrapperNet(policy_net, [n_actions]),
        # A tuple with an example of the input tensors
        (example_inp, torch.ones(1, n_actions)),
        'model.onnx',
        opset_version=9,
        # input_names must correspond to the WrapperNet forward parameters
        input_names=["obs_0", "action_masks"],
        # output_names must correspond to the return tuple of the WrapperNet
        # forward function.
        output_names=["discrete_actions", "discrete_action_output_shape",
                      "version_number", "memory_size"],
        # All inputs and outputs should have their 0th dimension designated
        # as 'batch'
        dynamic_axes={'obs_0': {0: 'batch'},
                      'action_masks': {0: 'batch'},
                      'discrete_actions': {0: 'batch'},
                      'discrete_action_output_shape': {0: 'batch'},
                      }
    )


"""OPTIMIZE:"""


def optimize_model(i_episode):
    if len(memory) < BATCH_SIZE:
        return
    """Sample a batch from memory and create a batch variable as a dict with
     categories: batch[0] -> states, batch[1] -> actions, batch[2] -> next_state, batch[3] -> reward"""
    transitions = memory.sample(BATCH_SIZE)
    batch = Transition(*zip(*transitions))

    """Find final and non-final next states from our batch of size 128."""
    non_final_mask = torch.tensor(tuple(map(lambda s: s is not None, batch.next_state)), device=device, dtype=torch.bool)
    non_final_next_states = torch.cat([s for s in batch.next_state if s is not None])

    """Make our data a 1-column tensor for state, action, reward."""
    state_batch = torch.cat(batch.state)
    action_batch = torch.cat(batch.action)
    reward_batch = torch.cat(batch.reward)

    """
    Calculate our policy max Q(s,a,z) and target max Q(s,a,z')
    (estimated optimal Q) and compute the loss function using Huber Loss.

    After that we continue by computing gradients and performing
    backpropagation to make an optimization step and update the weights of
    our policy network according to the direction of the gradients.
    """
    state_action_values = policy_net(state_batch).gather(1, action_batch)  # gathers actions received from agent.

    next_state_values = torch.zeros(BATCH_SIZE, device=device)

    with torch.no_grad():
        next_state_values[non_final_mask] = target_net(non_final_next_states).max(1).values

    expected_state_action_values = (next_state_values * GAMMA) + reward_batch

    criterion = nn.SmoothL1Loss()
    loss = criterion(state_action_values, expected_state_action_values.unsqueeze(1))

    writer.add_scalar("loss/training", loss, i_episode)

    optimizer.zero_grad()
    loss.backward()

    torch.nn.utils.clip_grad_value_(policy_net.parameters(), 100)
    optimizer.step()


"""
Inference loop: use the trained model to evaluate the agent's behavior.
It also prints the last policy in the terminal to test whether the agent
converges to a rational policy.
"""


def inference_loop(model):
    inf_policy = []
    for i_episode in range(20):
        inf_policy = []
        state = env.reset()
        state = torch.tensor(state, dtype=torch.float32, device=device).unsqueeze(0)

        for t in count():
            action = model(state).max(1).indices.view(1, 1)
            observation, reward, terminated, info = env.step(action.item())
            reward = torch.tensor([reward], device=device)
            done = terminated

            if terminated:
                next_state = None
            else:
                inf_policy.append(action)
                next_state = torch.tensor(observation, dtype=torch.float32, device=device).unsqueeze(0)

            state = next_state

            if done:
                break
    print(inf_policy)


""" Main training loop: """


def training_loop():
    plot_reward_array = []
    plot_episode_array = []
    temp_rewards = []

    for i_episode in range(num_episodes):

        # init environment and get state. Convert state to a tensor and add a dimension for tensor operations
        state = env.reset()
        state = torch.tensor(state, dtype=torch.float32, device=device).unsqueeze(0)  # shape (1, n_observations)

        for t in count():
            action = select_action(state)
            # Make a step using the action returned from the eps-greedy policy and collect state, reward of next state
            observation, reward, terminated, info = env.step(action.item())

            temp_rewards.append(reward)  # For plot

            # Reward as tensor to use it in optimizer
            reward = torch.tensor([reward], device=device)
            done = terminated

            # Check if episode terminates:
            if terminated:
                next_state = None
            else:
                next_state = torch.tensor(observation, dtype=torch.float32, device=device).unsqueeze(0)

            """ Save our data as tensors in memory """
            memory.push(state, action, next_state, reward)
            state = next_state

            optimize_model(i_episode)

            target_net_state_dict = target_net.state_dict()
            policy_net_state_dict = policy_net.state_dict()

            """Slowly update our target network"""
            for key in policy_net_state_dict:
                target_net_state_dict[key] = policy_net_state_dict[key] * TAU + target_net_state_dict[key] * (1 - TAU)
            target_net.load_state_dict(target_net_state_dict)

            if done:
                print(f"Episode {i_episode}/{num_episodes}.")
                break

        # for plot:
        plot_reward_array.append(statistics.mean(temp_rewards))
        plot_episode_array.append(i_episode)
        temp_rewards = []
    writer.flush()

    print("Completed .. ")
    # Save model as .onnx file (for Unity)
    save_model_onnx()
    print(f".onnx model saved at {os.getcwd()}\\model.onnx")
    # Save model as dict for local usage
    torch.save(policy_net, os.getcwd()+'\\model.pth')
    print(f"model saved as .pth : {os.getcwd()}\\model.pth")
    plot_reward(plot_episode_array, plot_reward_array)


def main(args):

    if(args.inference):
        print("Loading last trained model..")

        # Load our last trained model from a .pth file
        model = torch.load(os.getcwd() + '\\' + args.modelname)
        print(f"Model : {model}. Loaded")
        # Do not use grads
        model.eval()
        inference_loop(model)
    else:
        training_loop()


if __name__ == "__main__":
    main(args)
