""" Initialize device to compute tensor calculations
(CPU used) and the rest of the parameters of the DQN algorithm"""

device = torch.device("cuda" if torch.cuda.is_available() else "cpu")

Transition = namedtuple('Transition', ('state', 'action', 'next_state', 'reward'))

""" Choose num of episodes according to the device.
Default is 500 for both."""

